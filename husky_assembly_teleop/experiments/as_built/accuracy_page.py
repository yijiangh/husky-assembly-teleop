# * ================================================================ the whole page

def render(day: Mapping, runs: Sequence[Mapping]) -> str:
    """The whole page of one day."""
    pretty = datetime.strptime(day["day"], "%Y%m%d").strftime("%-d %b %Y")
    flat = flat_records(day["actions"])
    measured, without = bars_measured(day["raw"]), bars_without_markers(day["raw"])
    robots = list(dict.fromkeys((record.get("robot") or "").capitalize() for record in day["raw"]
                                if record.get("robot")))
    run_ids = list(dict.fromkeys(record.get("run_id") for record in day["raw"] if record.get("run_id")))
    stamps = [(record.get("stamp") or "T")[11:19] for record in day["raw"]]
    data = (f"{len(day['raw'])} as-built records, {stamps[0]}–{stamps[-1]} · {len(runs)} servo runs · {len(run_ids)} "
            f"run{'' if len(run_ids) == 1 else 's'} · {'old' if day['old'] else 'new'} monitor's format")
    fields = [("Process", f'<span class="mono">{esc(day["problem"])}</span>'), ("Day", esc(day["day"])),
              ("Bars", f"Measured: {esc(', '.join(measured) or 'none')} · without markers: "
                       f"{esc(', '.join(without) or 'none')}"),
              ("Robots", esc(" · ".join(robots) or "none")), ("Data", esc(data)),
              ("Left out", "A bar still on its loading spot, and any pair of records without a fit or a target")]
    rows = [*servo_step_rows(runs), *step_changes(day["actions"])]
    body = (titleblock("Three-robot assembly test · as-built numbers", f"As-built accuracy, {pretty}", GENERATED,
                       fields)
            + changes_section(rows) + placed_section(placed_motion(day["actions"])) + servo_section(runs)
            + settings_section(day) + fit_section(fit_quality(day["raw"]))
            + section("Method", "How the numbers are made", "", method(METHOD))
            + f"<footer>Built {datetime.now().isoformat(timespec='seconds')} from {esc(day['source_file'])} "
              f"({len(flat)} records on the schedule).</footer>")
    return page(f"As-built accuracy, {pretty}", body)


def build_report(drive_root: Path, day: str | None = None, problem: str | None = None,
                 process_folder: Path | None = None, out: Path | None = None) -> Path:
    """Build the accuracy report of one lab day and return its path.

    Args:
        drive_root: The Drive root the records are under.
        day: YYYYMMDD; default the newest day with records.
        problem: The process folder's name; default the day's newest file's.
        process_folder: The process folder; default `<drive>/data_design_study/<problem>`.
        out: The .html to write; default `<drive>/.../<day>-asbuilt-result/accuracy_<day>.html`.

    Raises:
        SystemExit: No records.
    """
    drive_root = Path(drive_root)
    if day is None:
        days = as_built_days(drive_root)
        if not days:
            raise SystemExit(f"no as-built records under {drive_root / AS_BUILT_FOLDER}")
        day = days[-1]
    if problem is None:
        problems = as_built_problems(drive_root, day)
        if not problems:
            raise SystemExit(f"no as-built file in {drive_root / AS_BUILT_FOLDER / (day + DIR_SUFFIX)}")
        problem = problems[0]
    data = read_day(drive_root, day, problem, process_folder)
    runs = read_servo_runs(data, drive_root)
    print(f"[assembly] {len(data['raw'])} records of {problem} on {day}, {len(runs)} servo runs.")
    return write(render(data, runs), Path(out) if out else result_folder(drive_root, day) / f"accuracy_{day}.html")
