#: The servo panels' colours by what they draw, in the fixed order of the sheet's series.
SERIES_COLOUR = {"bar": "var(--s1)", "left": "var(--s2)", "arm": "var(--s2)", "right": "var(--s3)"}
SERIES_LABEL = {"bar": "bar, from its markers", "left": "left flange", "arm": "flange (one arm)",
                "right": "right flange"}
GENERATED = ("This page is generated by <span class=\"mono\">scripts/as_built_report.py</span>. It gives measurements "
             "without conclusions.")


# * ================================================================ what each step did

def step_label(row: Mapping) -> str:
    """A row's bar, with its try when the bar went through this kind of step more than once."""
    return f"{row['bar']} · try {row['try']}" if row["tries"] > 1 else row["bar"]


def _how(row: Mapping) -> str:
    """A step row's time and outcome in a few words."""
    span = row["to"] if row["from"] == row["to"] else f"{row['from']}–{row['to']}"
    outcome = row.get("outcome")
    return f"{span}" + (f" · {outcome}" if outcome not in (None, "ok", "converged", "done") else "")


def change_rows(rows: Sequence[Mapping]) -> str:
    """The change per step as horizontal bars around zero, one group per kind of step, all on one scale."""
    if not rows:
        return '<p class="muted">No pair of records with the bar measured in both.</p>'
    low, high = min(0.0, *(row["change"] for row in rows)), max(0.0, *(row["change"] for row in rows))
    width = (high - low) or 1.0
    zero = (0.0 - low) / width * 100.0
    groups = []
    for key, (title, how) in GROUPS.items():
        lines = []
        for row in (row for row in rows if row["group"] == key):
            size = abs(row["change"]) / width * 100.0
            left = zero - size if row["change"] < 0 else zero
            tip = (f"{step_label(row)} · {title}\n{row['movement']}\n{_how(row)}\n"
                   f"before {row['before']:.2f} mm, after {row['after']:.2f} mm, change {row['change']:+.2f} mm")
            mark = "down" if row["change"] < 0 else "up"
            lines.append(
                f'<div class="bar-row" data-tip="{esc(tip)}"><span class="bar-label">{esc(step_label(row))}'
                f"<small>{esc(_how(row))}</small></span>"
                f'<span class="bar-track"><i class="zero" style="left:{zero:.2f}%"></i>'
                f'<i class="mark {mark}" style="left:{left:.2f}%;width:{size:.2f}%"></i></span>'
                f'<span class="bar-vals">{row["before"]:.2f} → {row["after"]:.2f} <b>{row["change"]:+.2f}</b></span>'
                "</div>")
        if lines:
            groups.append(f'<div class="bar-group"><h3>{esc(title)} <small>{esc(how)}</small></h3>{"".join(lines)}'
                          "</div>")
    axis = f'<div class="bar-axis"><span>{low:+.1f} mm</span><span>{high:+.1f} mm</span></div>'
    return axis + f'<div class="bars">{"".join(groups)}</div>'


def changes_section(rows: Sequence[Mapping]) -> str:
    """Section: what each step did to the bar being built."""
    ordered = sorted(rows, key=lambda row: (list(GROUPS).index(row["group"]), row["epoch"] or 0.0))
    numbers = table(
        [("Step", ""), ("Bar", ""), ("Movement", ""), ("From", ""), ("To", ""), ("Before, mm", "n"), ("After, mm", "n"),
         ("Change, mm", "n"), ("Outcome", "")],
        [[(esc(GROUPS[row["group"]][0]), ""), (esc(step_label(row)), ""), (esc(row["movement"]), "mono"),
          (esc(row["from"]), "time"), (esc(row["to"]), "time"), (number(row["before"]), "n"),
          (number(row["after"]), "n"), (f"{row['change']:+.2f}", "n"), (esc(row.get("outcome") or ""), "")]
         for row in ordered])
    chart = ('<figure class="chart"><figcaption><b>Change in placement error, by step</b><span>Beside each bar: the '
             "error before and after the step, then the change, in mm.</span></figcaption>"
             '<div class="chart-legend" aria-hidden="true"><span><i class="box" style="background:var(--down)"></i>'
             'error went down</span><span><i class="box" style="background:var(--up)"></i>error went up</span></div>'
             f"{change_rows(ordered)}<details><summary>Show the numbers</summary>{numbers}</details></figure>")
    return section("Analysis 1", "What each step did to the bar being built",
                   "The placement error is the largest of the distances at the bar's start, middle and end between the "
                   "MoCap bar and where it should be at that moment, as on the 3D page. A pair of records where either "
                   "has no fit or no target is left out; the fit table below says which bars those are.", chart)


# * ================================================================ bars already in place

def _heat(value: float | None, scale: float, tip: str) -> tuple[str, str]:
    """A table cell shaded by how large its value is on the table's scale."""
    if value is None:
        return "·", "n z"
    share = min(value / scale, 1.0) * 60.0 if scale > 0 else 0.0
    return (f'<span data-tip="{esc(tip)}" style="display:block;margin:-9px -12px;padding:9px 12px;'
            f'background:color-mix(in oklab, var(--s1) {share:.0f}%, var(--sheet))">{value:.2f}</span>'), "n"


def placed_section(motion: Mapping) -> str:
    """Section: how far each bar in place moved at each later event, with a still pair for scale."""
    bars = motion["bars"]
    intro = ("How far the start or the end of a bar in place moved over each later event, whichever moved more, in mm; "
             "hover a cell for both. A bar counts from its release until it is built again, or from its first record "
             f"when it is first seen within {IN_PLACE_MM:.0f} mm of its seat.")
    if not motion["events"]:
        return section("Analysis 2", "Bars already in place", intro,
                       '<p class="muted">No bar in place in these records yet: nothing to show.</p>')
    scale = max((max(values) for event in motion["events"] for values in event["moved"].values()), default=1.0)
    headers = [("Event", ""), ("From", ""), ("To", ""), *((bar, "n") for bar in bars)]
    rows = []
    still = motion.get("still")
    if still:
        rows.append([("<b>Still pair, for scale</b><br><small>no step ran between these two records, and of all such "
                      f"pairs the bars moved least here ({still['seconds']:.0f} s apart)</small>", ""),
                     (esc(still["from"]), "time"),
                     (esc(still["to"]), "time"), *(_cell(still["moved"].get(bar), bar, scale) for bar in bars)])
    for event in motion["events"]:
        outcome = event.get("outcome")
        words = esc(event["title"]) + (f" <small>{esc(outcome)}</small>" if outcome not in (None, "ok") else "")
        rows.append([(f"{words}<br><small>{esc(event.get('robot') or '')}</small>", ""), (esc(event["from"]), "time"),
                     (esc(event["to"]), "time"), *(_cell(event["moved"].get(bar), bar, scale) for bar in bars)])
    since = table(
        [("Bar", ""), ("In place from", ""), ("Last measured", ""), ("Start moved, mm", "n"), ("End moved, mm", "n"),
         ("Placement error then, mm", "n"), ("Placement error last, mm", "n")],
        [[(esc(bar), ""), (esc(slot["from"]), "time"), (esc(slot["to"]), "time"), (number(slot["moved"][0]), "n"),
          (number(slot["moved"][1]), "n"), (number(slot["error_from"]), "n"), (number(slot["error_to"]), "n")]
         for bar, slot in motion["since"].items()])
    return section("Analysis 2", "Bars already in place", intro,
                   table(headers, rows) + '<div class="section-head sub"><h3>Over the whole day</h3></div>' + since)


def _cell(moved: Sequence[float] | None, bar: str, scale: float) -> tuple[str, str]:
    """One bar's cell of one event."""
    if moved is None:
        return _heat(None, scale, "")
    return _heat(max(moved), scale, f"{bar}: start moved {moved[0]:.2f} mm, end moved {moved[1]:.2f} mm")


# * ================================================================ the servo

def servo_series(run: Mapping) -> dict[str, list]:
    """A run's lines to draw: {bar, left, right or arm: a value per reading (None where not measured)}."""
    series: dict[str, list] = {}
    if any(reading["bar_mm"] is not None for reading in run["passes"]):
        series["bar"] = [reading["bar_mm"] for reading in run["passes"]]
    sides = [side for reading in run["passes"] for side in reading["flanges"]]
    for side in dict.fromkeys(sides):
        series[side] = [reading["flanges"].get(side) for reading in run["passes"]]
    return series


def servo_panel_svg(run: Mapping, top: float) -> str:
    """One run's small chart: the error per reading, on the scale all panels share (0 to `top`, mm)."""
    width, height, left, right, above, below = 260, 120, 30, 6, 6, 16
    passes = len(run["passes"])
    x = (lambda k: left + (width - left - right) * (k / (passes - 1) if passes > 1 else 0.5))
    y = (lambda value: height - below - (height - above - below) * min(value, top) / top)
    grid = "".join(f'<line x1="{left}" x2="{width - right}" y1="{y(tick):.1f}" y2="{y(tick):.1f}" '
                   f'stroke="var(--rule)" stroke-width="1"/><text x="{left - 4}" y="{y(tick) + 3:.1f}" '
                   f'text-anchor="end">{tick:g}</text>' for tick in (0.0, top / 2.0, top))
    ticks = "".join(f'<text x="{x(k):.1f}" y="{height - 3}" text-anchor="middle">{k}</text>'
                    for k in sorted({0, passes - 1}) if passes)
    marks = []
    for name, values in servo_series(run).items():
        colour = SERIES_COLOUR.get(name, "var(--s2)")
        known = [(k, value) for k, value in enumerate(values) if value is not None]
        if len(known) > 1:
            points = " ".join(f"{x(k):.1f},{y(value):.1f}" for k, value in known)
            marks.append(f'<polyline points="{points}" fill="none" stroke="{colour}" stroke-width="2" '
                         'stroke-linejoin="round"/>')
        for k, value in known:
            tip = f"{SERIES_LABEL.get(name, name)}, reading {k}: {value:.2f} mm"
            marks.append(f'<g data-tip="{esc(tip)}"><circle cx="{x(k):.1f}" cy="{y(value):.1f}" r="9" '
                         f'fill="transparent"/><circle cx="{x(k):.1f}" cy="{y(value):.1f}" r="3.5" fill="{colour}" '
                         'stroke="var(--sheet)" '
                         'stroke-width="1.5"/></g>')
    return (f'<svg viewBox="0 0 {width} {height}" role="img" aria-label="{esc(_panel_words(run))}">{grid}{ticks}'
            f'{"".join(marks)}</svg>')


def _panel_words(run: Mapping) -> str:
    """A run's outcome in words: its time, corrections, feedback and how it ended."""
    corrections = run["corrections"]
    words = f"{run['time'] or 'time unknown'} · {corrections} correction{'' if corrections == 1 else 's'}"
    words += f" · {run['feedback']}" if run["feedback"] else ""
    words += " · dry run" if run.get("dry_run") else ""
    ended = run["outcome"] or run["ended"]
    return f"{words} · {ended}" + (f": {run['reason']}" if run["reason"] else "")


def servo_section(runs: Sequence[Mapping]) -> str:
    """Section: per servo run, a small chart of the bar's and the flanges' errors by reading, and its outcome."""
    intro = ("Every servo run of the day. Reading 0 is the first measurement, before anything moved. The bar line is "
             "the placement error against the servo's target, drawn when the bar's fit was usable. A flange's line is "
             "its distance from its authored target, as the servo file says.")
    if not runs:
        return section("Analysis 3", "The servo, correction by correction", intro,
                       '<p class="muted">No servo file for this day.</p>')
    values = [value for run in runs for line in servo_series(run).values() for value in line if value is not None]
    top = float(math.ceil(max(values or [1.0])))
    panels = "".join(
        f'<div class="panel"><h4>{esc(run["movement"])}</h4>'
        f'{servo_panel_svg(run, top)}<p>{esc(_panel_words(run))}</p></div>' for run in runs if run["passes"])
    sides = list(dict.fromkeys(side for run in runs for reading in run["passes"] for side in reading["flanges"]))
    legend = "".join(f'<span><i style="border-color:{SERIES_COLOUR[name]}"></i>{esc(SERIES_LABEL[name])}</span>'
                     for name in ("bar", *sides) if name in SERIES_COLOUR)
    numbers = table(
        [("Time", ""), ("Bar", ""), ("Movement", ""), ("Reading", "n"), ("Bar, mm", "n"),
         *((f"{side} flange, mm", "n") for side in sides), *((f"{side} force, N", "n") for side in sides),
         ("Not usable because", "")],
        [[(esc(run["time"]), "time"), (esc(run["bar"]), ""), (esc(run["movement"]), "mono"),
          (esc(reading["iter"]), "n"), (number(reading["bar_mm"]), "n"),
          *((number(reading["flanges"].get(side)), "n") for side in sides),
          *((number(reading["forces"].get(side), 1), "n") for side in sides), (esc(reading["note"]), "")]
         for run in runs for reading in run["passes"]])
    figure = ('<figure class="chart"><figcaption><b>Error at each reading, mm</b><span>The same scale in every panel. '
              f'Hover a mark for its value.</span></figcaption><div class="chart-legend" aria-hidden="true">{legend}'
              f'</div><div class="multiples">{panels}</div><details><summary>Show the numbers</summary>{numbers}'
              "</details></figure>")
    return section("Analysis 3", "The servo, correction by correction", intro, figure)


# * ================================================================ settings and fits

def _box(box: Mapping) -> str:
    """One tick box of a step: used or not, how it was set, and what the record says about it."""
    used = "used" if box.get("used") else "unused"
    words = "used" if box.get("used") else "not used"
    setting = {True: "ticked", False: "unticked"}.get(box.get("box"), "not recorded")
    return (f'<span><span class="tick {used}">{words}</span> {esc(box["label"])} <small>{setting}: '
            f"{esc(box.get('why') or '')}</small></span>")


def settings_section(day: Mapping) -> str:
    """Section: the tick boxes each step used, and the settings in force over the day."""
    intro = "From each record's own <span class=\"mono\">settings</span> and <span class=\"mono\">options</span>."
    if day["old"]:
        return section("Settings", "Which settings each step used", intro,
                       '<p class="muted">The old monitor\'s records hold no settings or options, so this day has none '
                       "to show here.</p>")
    rows = step_options(day["actions"])
    steps = table(
        [("Time", ""), ("Action", ""), ("Movement", ""), ("Part", ""), ("Outcome", ""), ("Tick boxes", "")],
        [[(esc(row["time"]), "time"), (esc(row["action"]), ""), (esc(row["movement"]), "mono"),
          (esc(row["part"] or row["routine"] or ""), ""), (esc(row["outcome"] or ""), ""),
          (f'<div class="boxes">{"".join(_box(box) for box in row["boxes"])}</div>', "")] for row in rows])
    force = table(
        [("Setting", ""), ("Value", ""), ("From", ""), ("To", "")],
        [[(esc(item["key"]), "mono"), (esc(span["value"]), "mono"), (esc(span["from"]), "time"),
          (esc(span["to"]), "time")] for item in settings_in_force(day["raw"]) for span in item["spans"]])
    return section("Settings", "Which settings each step used", intro,
                   steps + '<div class="section-head sub"><h3>Settings in force, by time</h3></div>' + force)


def fit_section(rows: Sequence[Mapping]) -> str:
    """Section: each bar's fits, flagging those under N markers or above the rms limit."""
    cells = []
    for row in rows:
        matched = sorted(set(row["matched"]))
        span = "–" if not matched else (f"{matched[0]}" if len(matched) == 1 else f"{matched[0]}–{matched[-1]}")
        flags = ""
        if row["under_n"]:
            flags += f'<span class="flag">{row["under_n"]} under {row["design"]}</span>'
        if row["over_rms"]:
            flags += f'<span class="flag">{row["over_rms"]} above {FIT_RMS_TOL_MM:g} mm</span>'
        if row["failed"]:
            flags += f'<span class="flag">{row["failed"]} failed</span>'
        reasons = "<br>".join(f"<small>{count} × {esc(reason)}</small>" for reason, count in row["reasons"].items())
        cells.append([(esc(row["bar"]), ""), (str(row["records"]), "n"), (str(row["ok"]), "n"),
                      (str(row["failed"]), "n"), (f"{span} of {row['design']}", "n"), (number(row["rms_median"]), "n"),
                      (number(row["rms_max"]), "n"), (flags + ("<br>" if flags and reasons else "") + reasons, "")])
    return section("Fits", "Fit quality per bar",
                   f"Every record's fit of every bar with markers, the bars still on their loading spots too. Flagged: "
                   f"fits that matched under all the bar's markers, or with an rms above {FIT_RMS_TOL_MM:g} mm.",
                   table([("Bar", ""), ("Records", "n"), ("Fits", "n"), ("Failed", "n"), ("Matched", "n"),
                          ("Rms median, mm", "n"), ("Rms worst, mm", "n"), ("Flags", "")], cells))


